type PremiumFinancePlan struct {
	PolicyID       string  `json:"policy_id"`
	TotalPremium   float64 `json:"total_premium"`
	DownPayment    float64 `json:"down_payment"`
	FinancedAmount float64 `json:"financed_amount"`
	InterestRate   float64 `json:"interest_rate_annual"`
	Installments   int     `json:"installments"`
	MonthlyPayment float64 `json:"monthly_payment"`
	TotalCost      float64 `json:"total_cost"`
	APR            float64 `json:"apr"`
}

func calculatePremiumFinance(totalPremium float64, downPaymentPct float64, installments int) PremiumFinancePlan {
	// NAICOM allows premium financing; typical rate 18-24% p.a.
	annualRate := 0.22 // 22% p.a.
	monthlyRate := annualRate / 12

	downPayment := totalPremium * downPaymentPct
	financed := totalPremium - downPayment

	// Amortization formula: M = P * [r(1+r)^n] / [(1+r)^n - 1]
	if installments <= 0 { installments = 6 }
	power := math.Pow(1+monthlyRate, float64(installments))
	monthlyPayment := financed * (monthlyRate * power) / (power - 1)

	totalCost := downPayment + monthlyPayment*float64(installments)
	apr := (totalCost - totalPremium) / totalPremium * 100 / (float64(installments) / 12)

	return PremiumFinancePlan{
		TotalPremium:   totalPremium,
		DownPayment:    math.Round(downPayment*100) / 100,
		FinancedAmount: math.Round(financed*100) / 100,
		InterestRate:   annualRate * 100,
		Installments:   installments,
		MonthlyPayment: math.Round(monthlyPayment*100) / 100,
		TotalCost:      math.Round(totalCost*100) / 100,
		APR:            math.Round(apr*100) / 100,
	}
}

func handleCalculateFinancePlan(w http.ResponseWriter, r *http.Request) {
	if r.Method != http.MethodPost {
		http.Error(w, `{"error":"method not allowed"}`, http.StatusMethodNotAllowed)
		return
	}
	var req struct {
		PolicyID       string  `json:"policy_id"`
		TotalPremium   float64 `json:"total_premium"`
		DownPaymentPct float64 `json:"down_payment_pct"`
		Installments   int     `json:"installments"`
	}
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		http.Error(w, `{"error":"invalid request"}`, http.StatusBadRequest)
		return
	}
	if req.DownPaymentPct < 0.25 { req.DownPaymentPct = 0.25 } // Min 25% down
	result := calculatePremiumFinance(req.TotalPremium, req.DownPaymentPct, req.Installments)
	result.PolicyID = req.PolicyID
	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(result)
}

func main() {
	port := os.Getenv("PORT")
	if port == "" {
		port = "8130"
	}

	dsn := os.Getenv("DATABASE_URL")
	if dsn == "" {
		log.Fatal("FATAL: DATABASE_URL environment variable is required")
	}

	var err error
	db, err = sql.Open("postgres", dsn)
	if err != nil {
		log.Fatalf("Failed to open database: %v", err)
	}
	db.SetMaxOpenConns(25)
	db.SetMaxIdleConns(5)
	db.SetConnMaxLifetime(5 * time.Minute)

	if err = db.Ping(); err != nil {
		log.Printf("WARNING: Database not reachable at startup: %v", err)
	}

	// Auto-migrate
	_, err = db.Exec(`CREATE TABLE IF NOT EXISTS premium_finance_agreements (id SERIAL PRIMARY KEY, policy_id INTEGER NOT NULL, customer_id INTEGER NOT NULL, total_premium NUMERIC(20,2) NOT NULL, down_payment NUMERIC(20,2) NOT NULL, installments INTEGER DEFAULT 4, interest_rate NUMERIC(5,4) DEFAULT 0.05, monthly_amount NUMERIC(20,2), outstanding_balance NUMERIC(20,2), status VARCHAR(32) DEFAULT 'active', created_at TIMESTAMP DEFAULT NOW())`)
	if err != nil {
		jsonLog("warn", "migration error", "error", err.Error())
	}

	// Create indexes for foreign key columns and common query patterns
	indexSQL := []string{
		"CREATE INDEX IF NOT EXISTS idx_premium_finance_agreements_policy_id ON premium_finance_agreements(policy_id)", "CREATE INDEX IF NOT EXISTS idx_premium_finance_agreements_customer_id ON premium_finance_agreements(customer_id)",
	}
	for _, sql := range indexSQL {
		if _, err := db.Exec(sql); err != nil {
			log.Printf("WARNING: index creation: %v", err)
		}
	}

	rl := newRateLimiter(100, time.Minute)

	mux := http.NewServeMux()
	mux.HandleFunc("/health", handleHealth)
	mux.HandleFunc("/ready", handleReady)
	mux.HandleFunc("/live", handleLive)
	mux.HandleFunc("/stats", handleStats)
	mux.HandleFunc("/metrics", handlePrometheusMetrics)

	// Domain CRUD routes
	mux.HandleFunc("/api/v1/agreements", handleList)
	mux.HandleFunc("/api/v1/agreement", handleGetByID)
	mux.HandleFunc("/api/v1/agreements/create", handleCreate)
	mux.HandleFunc("/api/v1/agreements/delete", handleDelete)

	// Premium finance domain routes
	mux.HandleFunc("/api/v1/premium-finance/calculate", handleCalculateFinancePlan)

	// Apply middleware chain
	var handler http.Handler = mux
	handler = metricsMiddleware(handler)
	handler = rateLimitMiddleware(rl)(handler)
	handler = securityHeaders(handler)
	handler = otelMiddleware(corsMiddleware(handler))

	srv := &http.Server{
		Addr:         ":" + port,
		Handler:      handler,
		ReadTimeout:  15 * time.Second,
		WriteTimeout: 30 * time.Second,
		IdleTimeout:  60 * time.Second,
	}

	// Graceful shutdown
	go func() {
		sigCh := make(chan os.Signal, 1)
		signal.Notify(sigCh, syscall.SIGTERM, syscall.SIGINT)
		<-sigCh
		log.Println("Shutting down gracefully...")
		ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
		defer cancel()
		if err := srv.Shutdown(ctx); err != nil {
			log.Printf("Forced shutdown: %v", err)
		}
	}()

	log.Printf("Premium Finance Service starting on :%s", port)
	if err := srv.ListenAndServe(); err != nil && err != http.ErrServerClosed {
		log.Fatalf("Server failed: %v", err)
	}
}

// ─── Input Validation ────────────────────────────────────────────────────────

func validateQueryParam(r *http.Request, key string, maxLen int) (string, error) {
	val := r.URL.Query().Get(key)
	if len(val) > maxLen {
		return "", fmt.Errorf("parameter %s exceeds max length %d", key, maxLen)
	}
	return val, nil
}

func validateIntParam(r *http.Request, key string) (int, error) {
	val := r.URL.Query().Get(key)
	if val == "" {
		return 0, nil
	}
	n, err := strconv.Atoi(val)
	if err != nil {
		return 0, fmt.Errorf("parameter %s must be an integer", key)
	}
	return n, nil
}
