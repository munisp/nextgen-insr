"""Standalone Tweedie distribution tools via the adopted ``tweedie`` library.

Thin adapter over thequackdaddy/tweedie 0.0.9 (BSD-2-Clause) — the Python
port of the R ``tweedie`` package (Dunn & Smyth compound Poisson-gamma
evaluation; saddlepoint + Fourier series). Fills the standalone-Tweedie
gap: statsmodels GLM has the Tweedie *family* but not the full
distribution object (density/CDF/quantile).

Every path delegates to the real library (scipy rv_continuous subclass);
no density math is re-implemented here.

Acceptance golden: ``tweedie/tests/results.py`` in the upstream repo —
values generated by the R ``tweedie`` package (R 3.2.4, r70336, via
``tools/test_get_R_tweeide.R``); pinned in
``tests/data/tweedie_r_golden.json`` (F1 re-baseline, 2026-11).
"""

from __future__ import annotations

import numpy as np
from tweedie import tweedie as _tweedie

TWEEDIE_VERSION = "0.0.9"


def tweedie_density(y, mu: float, p: float, phi: float):
    """Tweedie pdf at ``y`` for mean ``mu``, power ``p``, dispersion ``phi``.

    Valid ranges follow the library: p<0 not supported here; p in [1,3]
    covers Poisson (p=1 boundary), compound Poisson-gamma (1<p<2), Gamma
    (p=2) and positive stable (p=3) families per Dunn & Smyth.
    """
    return _tweedie(p=p, mu=mu, phi=phi).pdf(y)


def tweedie_cdf(y, mu: float, p: float, phi: float):
    """Tweedie cdf at ``y`` (Fourier-series evaluation in the library)."""
    return _tweedie(p=p, mu=mu, phi=phi).cdf(y)


def tweedie_ppf(q, mu: float, p: float, phi: float):
    """Tweedie quantile function (inverse cdf) at probabilities ``q``."""
    return _tweedie(p=p, mu=mu, phi=phi).ppf(q)


def tweedie_loglikelihood(y, mu, p: float, phi) -> float:
    """Total Tweedie log-likelihood for observation/mean pairs.

    Usable directly by GLM pricing workflows (profile-likelihood scans over
    the variance power, deviance-based model comparison). Arrays are
    broadcast by the library.
    """
    y_arr = np.asarray(y, dtype=float)
    mu_arr = np.asarray(mu, dtype=float)
    phi_arr = np.asarray(phi, dtype=float)
    return float(
        np.sum(_tweedie(p=p, mu=mu_arr, phi=phi_arr).logpdf(y_arr))
    )


def power_variance_function(mu, p: float):
    """Tweedie power variance function Var = phi * mu^p evaluated at mu^p.

    The mean-variance relation that defines the Tweedie family; phi is
    scale-only and returned separately by ``tweedie_moments``.
    """
    return np.asarray(mu, dtype=float) ** p


def tweedie_moments(mu, p: float, phi) -> dict:
    """Analytic first two moments: mean = mu, var = phi * mu^p.

    (Dunn & Smyth 2005; also the definition used by statsmodels' Tweedie
    family — see freqsev/glm.py, var_power 1.6.)
    """
    mu_arr = np.asarray(mu, dtype=float)
    phi_arr = np.asarray(phi, dtype=float)
    return {
        "mean": mu_arr,
        "variance": phi_arr * np.power(mu_arr, p),
        "power": float(p),
    }
