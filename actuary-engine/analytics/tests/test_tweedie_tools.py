"""F1 acceptance: Tweedie density/CDF reproduce the R-generated references.

Golden source: thequackdaddy/tweedie tweedie/tests/results.py
(BSD-2-Clause), upstream commit f14a189d7cd80d41886041f44f40ae4db27d0067
(master tip 2021-09-09). Values generated by the R ``tweedie`` package
(R 3.2.4 Revised, 2016-03-16 r70336) via tools/test_get_R_tweeide.R; pinned
verbatim into tests/data/tweedie_r_golden.json (2026-11 F1 re-baseline,
54 cases: 54 density + 45 cdf).

Tolerance follows upstream's own test (tests/test_tweedie.py): density and
cdf asserted at rtol/atol 1e-8, EXCEPT the documented upstream exception
for power=3 cdf where the R reference values are anomalous (values drift
above 1 — upstream comments "I think the R function might be off here")
and upstream itself relaxes to rtol/atol 1e-3. We keep the same documented
exception; this is the honest-delta note for this golden.
"""

from __future__ import annotations

import numpy as np
import pytest
from numpy.testing import assert_allclose

from actuary_analytics.freqsev.tweedie_tools import (
    power_variance_function,
    tweedie_cdf,
    tweedie_density,
    tweedie_loglikelihood,
    tweedie_moments,
)

from .conftest import DATA


def _golden():
    import json

    with open(DATA / "tweedie_r_golden.json", encoding="utf-8") as fh:
        return json.load(fh)


GOLDEN = _golden()
YS = np.asarray(GOLDEN["ys"], dtype=float)
DENSITY_CASES = [(c["power"], c["mu"], c["phi"], c["density"])
                 for c in GOLDEN["cases"] if "density" in c]
CDF_CASES = [(c["power"], c["mu"], c["phi"], c["cdf"])
             for c in GOLDEN["cases"] if "cdf" in c]


@pytest.mark.parametrize("power,mu,phi,expected", DENSITY_CASES)
def test_density_reproduces_R_reference(power, mu, phi, expected):
    actual = tweedie_density(YS, mu=mu, p=power, phi=phi)
    assert_allclose(actual, np.asarray(expected, dtype=float), rtol=1e-8, atol=1e-8)


@pytest.mark.parametrize("power,mu,phi,expected", CDF_CASES)
def test_cdf_reproduces_R_reference(power, mu, phi, expected):
    actual = tweedie_cdf(YS, mu=mu, p=power, phi=phi)
    if power == 3:
        # Documented upstream exception: R reference values anomalous at
        # p=3; upstream's own test relaxes to 1e-3 here (see module docstring).
        tol = 1e-3
    else:
        tol = 1e-8
    assert_allclose(actual, np.asarray(expected, dtype=float), rtol=tol, atol=tol)


class TestMomentsAndVarianceFunction:
    def test_power_variance_function_hand_computed(self):
        # Var function mu^p evaluated by hand: mu=4, p=1.6 -> 4^1.6.
        assert np.isclose(power_variance_function(4.0, 1.6), 4.0 ** 1.6)
        arr = power_variance_function(np.array([1.0, 2.0, 3.0]), 2.0)
        assert_allclose(arr, np.array([1.0, 4.0, 9.0]))

    def test_tweedie_moments_hand_computed(self):
        # mean = mu; variance = phi * mu^p. mu=2, p=2, phi=3 -> var 12.
        m = tweedie_moments(2.0, 2.0, 3.0)
        assert m["mean"] == 2.0
        assert m["variance"] == 12.0
        assert m["power"] == 2.0

    def test_moments_match_frequency_severity_glm_convention(self):
        # statsmodels Tweedie(var_power=1.6) uses Var = phi * mu^1.6 — the
        # same relation exposed here (freqsev/glm.py GLMConfig).
        m = tweedie_moments(np.array([1.5, 2.5]), 1.6, 0.75)
        assert_allclose(m["variance"], 0.75 * np.array([1.5, 2.5]) ** 1.6)


class TestLoglikelihood:
    def test_loglikelihood_equals_sum_logpdf(self):
        ys = np.array([0.0, 1.0, 2.0, 5.0])
        mu = np.array([0.5, 0.5, 1.0, 1.0])
        total = tweedie_loglikelihood(ys, mu=mu, p=1.5, phi=0.75)
        from tweedie import tweedie

        ref = float(np.sum(tweedie(p=1.5, mu=mu, phi=np.repeat(0.75, 4)).logpdf(ys)))
        assert np.isclose(total, ref)
        assert np.isfinite(total)
